package io.element.android.libraries.audio.api

/**
 * Переключает звук на разговорный динамик, когда телефон поднесён к уху.
 *
 * VaVsta: нужно, чтобы голосовое сообщение можно было слушать как обычный звонок —
 * при приближении к уху звук идёт через телефонный канал (на разговорный динамик),
 * при удалении возвращается на обычный динамик приложения.
 *
 * На устройствах без proximity-датчика реализация обязана быть полностью no-op.
 */
interface ProximityAudioRouter {
    /**
     * Начать следить за proximity-датчиком.
     *
     * Вызывается, когда начинает играть голосовое сообщение. Повторный вызов, пока
     * слежение уже включено, игнорируется.
     */
    fun start()

    /**
     * Остановить слежение и вернуть обычный режим звука, если он был изменён.
     */
    fun stop()
}
